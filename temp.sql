SELECT 
    DATA_TIME,
    STANDARD_ID,
    FBB_ID,
    '' as USER_RADIUS,
    'FBB'  AS ACCOUNT_TYPE,
    CUSTOMER_PROFILE AS PACKAGE_NAME,
    PRICE AS PACKAGE_PRICE,
    APPLICATION_CATEGORY AS APP_CATEGORY,
    SVRID AS SVR_ID,
    APP_NAME,
    APPLICATION_PROTOCOL AS APP_PROTOCOL,
    SECO_PROID AS SECO_PROID,
    ACCESS_TIMES,
    TOTAL_TRAFFIC_MB,
    DL_TRAFFIC_MB,
    UL_TRAFFIC_MB,
    DURATION_HR  AS DURATION_HOUR,
    DURATION_RATIO,
    FIRST_USE_TIME,
    LAST_USE_TIME
FROM raw_app_sense.APPSENSE_APP_CATEGORY_DAILY_FBB_DAILY AS SRC
LEFT JOIN public.VIEW_STANDARDID_MAPPING_5MIN 
ON SRC.FBB_ID = public.VIEW_STANDARDID_MAPPING_5MIN.SUBSCRIBER_NO 
    AND concat(left(to_date(SRC.DATA_TIME,"yyyy-MM-dd"),10),' 23:59:59') between public.VIEW_STANDARDID_MAPPING_5MIN.EFFECTIVE_DATETIME AND public.VIEW_STANDARDID_MAPPING_5MIN.EXPIRE_DATETIME
;

SELECT 
    DATA_TIME,
    case 
        when ( TBB.FBB_ID is not null and TBB.REFERENCE_ACCOUNT_NUM is not null ) or ( TBB.FBB_ID is  null and TBB.REFERENCE_ACCOUNT_NUM is not null ) then TBB.STANDARD_ID
        when ( TBB1.FBB_ID is not null and TBB1.REFERENCE_ACCOUNT_NUM is not null ) or ( TBB1.FBB_ID is  null and TBB1.REFERENCE_ACCOUNT_NUM is not null ) then TBB1.STANDARD_ID
        else null 
    end as STANDARD_ID,
    case 
        when ( TBB.FBB_ID is not null and TBB.REFERENCE_ACCOUNT_NUM is not null ) or ( TBB.FBB_ID is  null and TBB.REFERENCE_ACCOUNT_NUM is not null ) then TBB.FBB_ID
        when  ( TBB1.FBB_ID is not null and TBB1.REFERENCE_ACCOUNT_NUM is not null ) or ( TBB1.FBB_ID is  null and TBB1.REFERENCE_ACCOUNT_NUM is not null ) then TBB1.FBB_ID
        else null 
    end as FBB_ID,
    SRC.FBB_ID as USER_RADIUS,
    '3BB'  AS ACCOUNT_TYPE,
    CUSTOMER_PROFILE AS PACKAGE_NAME,
    PRICE AS PACKAGE_PRICE,
    APPLICATION_CATEGORY AS APP_CATEGORY,
    SVRID AS SVR_ID,
    APP_NAME,
    APPLICATION_PROTOCOL AS APP_PROTOCOL,
    SECO_PROID AS SECO_PROID,
    ACCESS_TIMES,
    TOTAL_TRAFFIC_MB,
    DL_TRAFFIC_MB,
    UL_TRAFFIC_MB,
    DURATION_HR AS DURATION_HOUR,
    DURATION_RATIO,
    FIRST_USE_TIME,
    LAST_USE_TIME
  FROM 
    (
      SELECT * FROM raw_app_sense.APPSENSE_APP_CATEGORY_DAILY_3BB_DAILY
    ) AS SRC
  --LEFT JOIN H005_OUT ON SRC.APP_NAME = argument
  LEFT JOIN (SELECT * FROM (SELECT public.FACT_STANDARDID_TBB_MAPPING.*,ROW_NUMBER() OVER(PARTITION BY USER_RADIUS ORDER BY EFFECTIVE_DATE DESC,FBB_ID) AS ROW_NUM FROM public.FACT_STANDARDID_TBB_MAPPING) AS B
              WHERE ROW_NUM =1
            ) AS TBB
  ON SRC.FBB_ID = TBB.USER_RADIUS 
  LEFT JOIN (SELECT * FROM (SELECT public.FACT_STANDARDID_TBB_MAPPING.*,ROW_NUMBER() OVER(PARTITION BY USER_RADIUS ORDER BY EFFECTIVE_DATE DESC,FBB_ID) AS ROW_NUM FROM public.FACT_STANDARDID_TBB_MAPPING) AS B
              WHERE ROW_NUM =1 or USER_RADIUS is null
            ) AS TBB1
ON SRC.PREFIX_NO = TBB1.BB_NO
;